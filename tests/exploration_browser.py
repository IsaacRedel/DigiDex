"""Execute com npm run build e npm run preview ativos na porta 4173."""
import json,tempfile
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
artifacts=Path(tempfile.mkdtemp(prefix='digidex-exploration-'))
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
 page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:4173',wait_until='networkidle')
 expect(page.locator('.digi-card')).to_have_count(66)
 page.get_by_label('Coleção',exact=True).first.select_option('tamers')
 expect(page.locator('.digi-card')).to_have_count(12)
 page.locator('#search').fill('guilmon');expect(page.locator('.digi-card')).to_have_count(1)
 page.get_by_role('link',name='Ver ficha de Guilmon',exact=True).click()
 expect(page.locator('#detail-name')).to_have_text('Guilmon')
 expect(page.locator('.profile-context')).to_contain_text('necessariamente maligno')
 page.get_by_role('button',name='Explorar Gallantmon',exact=True).click()
 expect(page.locator('#detail-name')).to_have_text('Gallantmon')
 page.keyboard.press('Escape');page.wait_for_function("document.body.style.overflow === ''")
 page.get_by_role('button',name='Limpar busca e filtros').click()
 page.locator('#map-collection').select_option('tamers')
 expect(page.locator('.map-node')).to_have_count(4)
 expect(page.locator('#map-context')).to_contain_text('Tamers')
 page.locator('#map-line').select_option('renamon')
 expect(page.locator('.map-node').last).to_contain_text('Sakuyamon')
 page.locator('#map-scale').fill('130');expect(page.locator('#scale-value')).to_have_text('130%')
 page.get_by_role('button',name='Abrir Sakuyamon',exact=True).click()
 expect(page.locator('#detail-name')).to_have_text('Sakuyamon')
 page.keyboard.press('Escape');page.wait_for_function("document.body.style.overflow === ''")
 page.locator('#map-collection').select_option('adventure')
 expect(page.locator('#map-fusion')).to_contain_text('Omegamon')
 page.locator('#exploration').scroll_into_view_if_needed()
 page.screenshot(path=str(artifacts/'map-desktop.png'))
 page.get_by_role('tab',name='Comparar parceiros').click()
 page.locator('#compare-left').select_option('guilmon');page.locator('#compare-right').select_option('gallantmon')
 expect(page.locator('.comparison-table')).to_contain_text('Vírus')
 expect(page.locator('.comparison-table')).to_contain_text('Tamers')
 page.get_by_role('button',name='Trocar parceiros de lado').click()
 expect(page.locator('#compare-left')).to_have_value('gallantmon')
 page.screenshot(path=str(artifacts/'compare-desktop.png'))
 for width in [320,390,768,1024,1440]:
  page.set_viewport_size({'width':width,'height':844})
  assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'Overflow em {width}'
  if width==390:page.screenshot(path=str(artifacts/'compare-mobile.png'))
  page.get_by_role('tab',name='Evoluções').click()
  assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'Mapa transborda em {width}'
  if width==390:page.screenshot(path=str(artifacts/'map-mobile.png'))
  page.get_by_role('tab',name='Comparar parceiros').click()
 page.set_viewport_size({'width':390,'height':844})
 page.locator('#comparison-result').scroll_into_view_if_needed()
 page.screenshot(path=str(artifacts/'comparison-table-mobile.png'))
 page.set_viewport_size({'width':1440,'height':1000})
 page.get_by_role('button',name='Preparar uso offline').click()
 expect(page.locator('#offline-status')).to_contain_text('pronto para uso offline',timeout=90000)
 awaitable='navigator.serviceWorker.ready.then(() => true)'
 page.evaluate(awaitable)
 page.reload(wait_until='networkidle')
 page.wait_for_function('navigator.serviceWorker.controller !== null')
 page.get_by_role('button',name='Adicionar Agumon aos favoritos').click()
 context.set_offline(True)
 page.reload(wait_until='networkidle')
 expect(page.locator('.digi-card')).to_have_count(66)
 expect(page.locator('#favorite-count')).to_have_text('1')
 page.get_by_role('tab',name='Comparar parceiros').click()
 page.locator('#compare-left').select_option('renamon');page.locator('#compare-right').select_option('sakuyamon')
 expect(page.locator('.comparison-table')).to_contain_text('Sakuyamon')
 page.get_by_role('button',name='Selecionar Veemon',exact=True).click()
 expect(page.locator('#partner-name')).to_have_text('Veemon')
 page.wait_for_function("document.querySelector('#partner-image').complete && document.querySelector('#partner-image').naturalWidth > 0")
 assert not errors,errors
 browser.close()
 print(json.dumps({'status':'passed','catalog':66,'offline_reload':True,'errors':errors,'artifacts':str(artifacts)},ensure_ascii=False))
